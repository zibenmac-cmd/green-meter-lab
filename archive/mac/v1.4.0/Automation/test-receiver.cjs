'use strict';
const assert = require('node:assert/strict');
const normalize = require('./normalize-summary.cjs');
const now = Date.now();
const base = { timestamp: new Date(now).toISOString(), session_id: 'receiver-test', source: 'device_raw_adc', device_id: 'meter-01', calibrated: false, voltage_adc_rms: 119.4, current_adc_rms: 17.9, received_points: 6400, power_w: null, energy_kwh: null };
assert.equal(normalize(base, now).load_state, '待标定');
assert.equal(normalize({...base, calibrated: undefined}, now).ok, false);
assert.equal(normalize({...base, power_w: 123}, now).ok, false);
assert.equal(normalize({...base, current_adc_rms: Infinity}, now).ok, false);
assert.equal(normalize({...base, timestamp: 'bad'}, now).ok, false);
assert.equal(normalize({...base, source: 'loopback_test_NOT_hardware'}, now).test_data, true);
assert.equal(normalize({...base, timestamp: new Date(now - 60000).toISOString()}, now).stale, true);
const calibrated = {...base, source: 'mac_socket128', calibrated: true, power_w: 80, energy_kwh: 0.002, load_state: '运行中'};
assert.equal(normalize(calibrated, now).load_state, '运行中');
assert.equal(normalize({...calibrated, load_state: 'invented'}, now).load_state, '待判定');
assert.equal(normalize({...calibrated, power_w: -1}, now).ok, false);
assert.equal(normalize({...calibrated, energy_kwh: -1}, now).ok, false);
assert.equal(normalize(null, now).ok, false);
console.log('PASS: 12 receiver checks; synthetic input only.');
